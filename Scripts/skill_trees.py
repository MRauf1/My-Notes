class Graph:
    """Union of all converted trees: home tree per node, prerequisites per node."""

    def __init__(self, trees):
        self.trees = [t for t in trees if not t.legacy]
        self.home_tree = {}
        self.title = {}
        self.prereqs = {}
        self.order = {}
        self.chapter = {}  # position of the node's group in its home tree (source/chapter order)
        for t in self.trees:
            for idx, (i, title) in enumerate(t.home):
                self.home_tree[title] = t.name
                self.order[title] = (t.name, idx)
                g = t.group.get(i)
                self.chapter[title] = t.group_order.index(g) if g in t.group_order else len(t.group_order)
            self.title.update(t.titles())
        for t in self.trees:
            for a, b in t.edges:
                if a in self.title and b in self.title:
                    self.prereqs.setdefault(self.title[b], set()).add(self.title[a])

    def depth(self, title, memo=None, stack=()):
        memo = {} if memo is None else memo
        if title in memo:
            return memo[title]
        if title in stack:
            return 0  # cycle; reported by `check`
        ps = self.prereqs.get(title, ())
        d = 0 if not ps else 1 + max(self.depth(p, memo, stack + (title,)) for p in ps)
        memo[title] = d
        return d

    def can_attempt(self, data, title, k):
        need = prereq_need(k)
        return all(level_of(data, p) >= need for p in self.prereqs.get(title, ()))


def prereq_need(k):
    """Level every prerequisite needs before level k can be attempted (reach gating)."""
    return min(k, PREREQ_FLOOR) if k <= MASTERED else MASTERED


# ---------------------------------------------------------------- rendering

def tree_stats(tree, graph, data):
    titles = [t for _, t in tree.home]
    counts = [0] * (MAX_LEVEL + 1)
    planned = locked = rusty = 0
    for t in titles:
        lv = level_of(data, t)
        if lv < 0:
            planned += 1
            continue
        counts[lv] += 1
        if lv == 0 and not graph.can_attempt(data, t, 1):
            locked += 1
        if is_rusty(data, t):
            rusty += 1
    total = len(titles)
    mastered = sum(counts[MASTERED:])
    depth_pct = round(100 * sum(i * c for i, c in enumerate(counts)) / (MAX_LEVEL * total)) if total else 0
    # Same formula with L3 (Mastered) as the peak: levels above L3 count as L3.
    mastery_depth_pct = (round(100 * sum(min(i, MASTERED) * c for i, c in enumerate(counts)) / (MASTERED * total))
                         if total else 0)
    return dict(total=total, discovered=total - planned, planned=planned, mastered=mastered,
                depth=depth_pct, mastery_depth=mastery_depth_pct, counts=counts, locked=locked, rusty=rusty)


def frontier(graph, data, tree_name=None):
    """Attemptable nodes below Mastered, in progressive order: group (chapter) first, then prerequisite depth, then file order."""
    out = []
    for title, home in graph.home_tree.items():
        if tree_name and home != tree_name:
            continue
        lv = level_of(data, title)
        if 0 <= lv < MASTERED and graph.can_attempt(data, title, lv + 1):
            out.append(title)
    memo = {}
    out.sort(key=lambda t: (graph.chapter.get(t, 0), graph.depth(t, memo), graph.order[t]))
    return out


def review_pool(graph, data, tree_name=None):
    """Mastered nodes: rusty ones (rust check at current level) and ones that can still level up."""
    rusty, growing = [], []
    for title, home in graph.home_tree.items():
        if tree_name and home != tree_name:
            continue
        lv = level_of(data, title)
        if lv < MASTERED:
            continue
        if is_rusty(data, title):
            rusty.append(title)
        elif lv < MAX_LEVEL and graph.can_attempt(data, title, lv + 1):
            growing.append(title)
    rusty.sort(key=lambda t: str(data["nodes"][t].get("last_tested")))
    return rusty, growing


def research_spine(graph):
    """Research targets (research_targets.yaml) plus all their ancestors."""
    targets = []
    if TARGETS_FILE.exists():
        targets = [t for t in (yaml.safe_load(TARGETS_FILE.read_text(encoding="utf-8")) or []) if t in graph.home_tree]
    out = set(targets)
    for t in targets:
        out |= ancestors(graph, t)
    return out


def stretch(data, tree):
    return data.get("reach", {}).get("stretch", {}).get(tree, REACH_START)


def reach_pick(graph, data, tree_name=None, recent=()):
    """Reach anchor: the node below L3 (research spine first, then any tree) whose count of below-L3
    ancestors is closest to its tree's stretch (restricted to the ancestors of a recently failed anchor
    while descending).
    Returns (title, unverified_count) or None."""
    spine = research_spine(graph)
    cands = []
    for pool in (spine, graph.home_tree):  # spine first; once it has no attemptable node, every tree
        lv = {t: level_of(data, t) for t in pool}
        cands = [t for t in pool if 0 <= lv[t] < MASTERED and t not in recent
                 and (not tree_name or graph.home_tree.get(t) == tree_name)
                 and graph.can_attempt(data, t, lv[t] + 1)]
        if cands:
            break
    descend = data.get("reach", {}).get("descend")
    if descend in graph.home_tree:
        below = ancestors(graph, descend)
        cands = [t for t in cands if t in below] or cands
    if not cands:
        return None
    unv = {t: sum(1 for a in ancestors(graph, t) if 0 <= lv.get(a, level_of(data, a)) < MASTERED) for t in cands}
    best = min(cands, key=lambda t: (abs(unv[t] - stretch(data, graph.home_tree[t])), graph.chapter.get(t, 0), graph.order[t]))
    return best, unv[best]


def downward_targets(graph, data, title, limit=8):
    """Below-L3 ancestors (with notes) nearest to `title`: the nodes a reach quiz should exercise non-routinely."""
    seen, frontier_, out = {title}, [title], []
    while frontier_ and len(out) < limit:
        nxt = []
        for x in frontier_:
            for p in sorted(graph.prereqs.get(x, ())):
                if p not in seen:
                    seen.add(p)
                    nxt.append(p)
                    if 0 <= level_of(data, p) < MASTERED and len(out) < limit:
                        out.append(p)
        frontier_ = nxt
    return out


def pending_audits(data, recent=()):
    out = [(str(e.get("last_tested")), t) for t, e in data["nodes"].items()
           if e.get("audit") and e.get("audit") == e.get("level") and t not in recent and note_exists(t)]
    return [t for _, t in sorted(out)]


def update_reach(graph, data, title, k, result, clean):
    """Binary-search the stretch from a direct quiz tier on a node below L3 (L2+ tiers only)."""
    tree = graph.home_tree.get(title)
    if not tree or k < 2 or k > MASTERED:
        return ""
    r = data.setdefault("reach", {})
    s = stretch(data, tree)
    if clean:
        s = min(REACH_MAX, s * REACH_GROW)
        d = r.get("descend")
        if d in graph.home_tree and (title == d or title in ancestors(graph, d)):
            r.pop("descend")
    elif result == "incorrect":
        s = max(REACH_MIN, s / 2)
        r["descend"] = title
    else:  # partial: usually a gap in a prerequisite the part leaned on, so reach a little less far
        s = max(REACH_MIN, s * REACH_PARTIAL)
    r.setdefault("stretch", {})[tree] = round(s, 2)
    return f"stretch {tree}: {round(s, 1)}"


def node_class(graph, data, title):
    lv = level_of(data, title)
    if lv < 0:
        return "planned"
    if lv == 0 and not graph.can_attempt(data, title, 1):
        return "locked"
    return f"L{lv}"


def diagram(nodes, external, edges, graph, data):
    """One Mermaid flowchart: `nodes` and `external` are [(id, title)], edges [(a, b)]."""
    def decl(i, t):
        return f'    {i}["{t.replace(chr(34), "#quot;")}"]'

    out = ["```mermaid", "flowchart TD"] + ["    " + c for c in CLASS_DEFS]
    if external:
        out.append('    subgraph sg_prereqs["Prerequisites from other groups"]')
        out += ["    " + decl(i, t) for i, t in external]
        out.append("    end")
    out += [decl(i, t) for i, t in nodes]
    out += [f"    {a} --> {b}" for a, b in edges]
    classes = {}
    for i, t in external + nodes:
        classes.setdefault(node_class(graph, data, t), []).append(i)
        if is_rusty(data, t):
            classes.setdefault("rusty", []).append(i)
    for cls in ["planned", "locked"] + [f"L{k}" for k in range(MAX_LEVEL + 1)] + ["rusty"]:
        if classes.get(cls):
            out.append(f"    class {','.join(classes[cls])} {cls};")
    linked = [i for i, t in external + nodes if note_exists(t)]
    if linked:
        out.append(f"    class {','.join(linked)} internal-link;")
    out.append("```")
    return "\n".join(out)


def reached_counts(counts):
    """Nodes at level k or above, for each k: these only ever rise as nodes level up."""
    return [sum(counts[k:]) for k in range(len(counts))]


def level_table(counts):
    head = " | ".join(f"L{k} {LEVEL_NAMES[k]}" + (" ★" if k == MASTERED else "") for k in range(len(counts)))
    return [
        f"| | {head} |",
        "|---|" + "---:|" * len(counts),
        "| **At this level** | " + " | ".join(str(c) for c in counts) + " |",
        "| **Reached (this level or higher)** | " + " | ".join(str(c) for c in reached_counts(counts)) + " |",
    ]


def render_tree(tree, graph, data):
    if tree.legacy:
        return False
    titles = tree.titles()
    parts = []

    st = tree_stats(tree, graph, data)
    fr = frontier(graph, data, tree.name)[:5]
    rusty, _ = review_pool(graph, data, tree.name)
    stats = [
        STATS_BEGIN,
        f"**Mastered:** {st['mastered']} / {st['total']} · **Depth:** {st['depth']}% · **Mastery Depth:** {st['mastery_depth']}% · "
        f"**Discovered:** {st['discovered']} · **Planned:** {st['planned']} · "
        f"**Locked:** {st['locked']} · **Rusty:** {st['rusty']}",
        "",
        *level_table(st["counts"]),
        "",
        "**Next up:** " + (", ".join(f"[[{t}]]" for t in fr) if fr else "—"),
    ]
    if rusty:
        stats += ["", "**Rusty:** " + ", ".join(f"[[{t}]]" for t in rusty[:5])]
    stats += ["", LEGEND, STATS_END]
    parts.append("\n".join(stats))

    for g in tree.group_order:
        nodes = [(i, t) for i, t in tree.home if tree.group[i] == g]
        ids = {i for i, _ in nodes}
        edges = [(a, b) for a, b in tree.edges if b in ids]
        ext_ids = []
        for a, _ in edges:
            if a not in ids and a not in ext_ids:
                ext_ids.append(a)
        external = [(i, titles[i]) for i in ext_ids if i in titles]
        levels = [level_of(data, t) for _, t in nodes]
        discovered = sum(1 for lv in levels if lv >= 0)
        reached = " · ".join(f"L{k} {sum(1 for lv in levels if lv >= k)}" for k in range(1, MAX_LEVEL + 1))
        planned = len(nodes) - discovered
        parts.append(f"## {g}\n**Reached:** {reached} (of {len(nodes)} nodes" + (f", {planned} planned" if planned else "") + ")\n\n"
                     + diagram(nodes, external, edges, graph, data))

    source, in_state = [], False
    for l in tree.source:
        s_ = l.strip()
        if s_.startswith("%% BEGIN STATE"):
            in_state = True
        if in_state:
            in_state = s_ != STATE_END
            continue
        if s_.startswith("flowchart") or s_.startswith("classDef") or s_.startswith("class "):
            continue
        source.append(l)
    parts.append("# Source\n" + SOURCE_NOTE + "\n\n" + SOURCE_OPEN + "\n" + "\n".join(source).rstrip("\n") + "\n```\n")
    text = "\n\n".join(parts)
    if text != tree.text:
        tree.path.write_text(text, encoding="utf-8")
    return True


