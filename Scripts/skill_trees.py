    "classDef locked fill:#334155,stroke:#475569,stroke-width:2px,color:#94A3B8;",
    "classDef L0 fill:#F1F5F9,stroke:#94A3B8,stroke-width:2px,color:#000000;",
    "classDef L1 fill:#22C55E,stroke:#15803D,stroke-width:2px,color:#000000;",
