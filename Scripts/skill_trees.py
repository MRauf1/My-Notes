def insert_line(text, after_marker, line, before_marker):
    """Insert line at the end of the section that starts with after_marker."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip() == after_marker)
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip().startswith(before_marker))
    lines.insert(end, line)
    return "\n".join(lines)


def declare(text, title, section, group=None):
    label = title.replace('"', "#quot;")
    line = f'    {node_id(title)}["{label}"]'
    if section == "PREREQUISITES":
        return insert_line(text, "%% PREREQUISITES", line, "%% NODES")
    if group:
        header = f"    %% == {group} =="
        lines = text.split("\n")
        if header not in lines:
            text = insert_line(text, "%% NODES", header, "%% EDGES")
            lines = text.split("\n")
        start = lines.index(header)
        end = start + 1
        while end < len(lines) and not lines[end].strip().startswith(("%% ==", "%% EDGES")):
            end += 1
        lines.insert(end, line)
        return "\n".join(lines)
    return insert_line(text, "%% NODES", line, "%% EDGES")


def add_edge_text(text, a, b):
    line = f"    {node_id(a)} --> {node_id(b)}"
    if line in text.split("\n"):
        return text
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip() == "%% EDGES")
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip().startswith(("```", "%% BEGIN STATE")))
    lines.insert(end, line)
    return "\n".join(lines)


def cmd_add(args):
    trees = load_trees()
    graph = Graph(trees)
    path = TREES_DIR / f"{args.tree}.md"
    if not path.exists():
        if not args.create:
            sys.exit(f"No tree '{args.tree}'. Pass --create to start a new one.")
        path.write_text(new_tree_text(), encoding="utf-8")
        trees = load_trees()
        graph = Graph(trees)
    tree = Tree(path)
    if tree.legacy:
        sys.exit(f"'{args.tree}' is a legacy tree; convert it first.")
    home = graph.home_tree.get(args.title)
    if home and home != args.tree:
        sys.exit(f"'{args.title}' already lives in tree '{home}'.")
    missing = [p for p in args.prereq if p not in graph.home_tree]
    if missing:
        sys.exit("Prerequisites not in any tree yet (add them first): " + "; ".join(missing))
    text = tree.text
    existing = tree.titles()
    if not home:
        text = declare(text, args.title, "NODES", args.group)
    for p in args.prereq:
        if graph.home_tree[p] != args.tree and node_id(p) not in existing:
            text = declare(text, p, "PREREQUISITES")
            existing[node_id(p)] = p
        text = add_edge_text(text, p, args.title)
    path.write_text(text, encoding="utf-8")
    render_all()
    print(f"Added '{args.title}' to {args.tree}" + (f" with prerequisites: {', '.join(args.prereq)}" if args.prereq else ""))


