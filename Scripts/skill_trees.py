def check_one(path):
    """Read-only structural check of a single tree file (safe while other trees are being edited)."""
    t = Tree(path)
    if t.legacy:
        return [f"{t.name}: no '%% NODES' marker (legacy format)"]
    problems = []
    ids = t.titles()
    seen = set()
    for i, title in t.external + t.home:
        if i != node_id(title):
            problems.append(f"id '{i}' should be '{node_id(title)}' for '{title}'")
        if i in seen:
            problems.append(f"node '{title}' declared twice")
        seen.add(i)
    for i, title in t.external:
        if not note_exists(title):
            problems.append(f"prerequisite '{title}' has no note (external prerequisites must be existing notes)")
    for a, b in t.edges:
        for x in (a, b):
            if x not in ids:
                problems.append(f"edge uses undeclared node '{x}'")
    used = {x for e in t.edges for x in e}
    for i, title in t.external:
        if i not in used:
            problems.append(f"prerequisite '{title}' is declared but has no edge")
    prereqs = {}
    for a, b in t.edges:
        prereqs.setdefault(b, set()).add(a)
    state = {}

    def visit(n, path):
        if state.get(n) == 1:
            problems.append("cycle: " + " -> ".join(ids.get(x, x) for x in path + [n]))
            return
        if state.get(n) == 2:
            return
        state[n] = 1
        for q in prereqs.get(n, ()):
            visit(q, path + [n])
        state[n] = 2

    for n in ids:
        visit(n, [])
    for l in t.source:
        s_ = l.strip()
        if s_ and not s_.startswith(("%%", "flowchart", "classDef", "class ")) \
                and not NODE_RE.match(l) and not EDGE_RE.match(l):
            problems.append(f"unrecognized line: {s_[:80]}")
    home_with_note = sum(1 for _, x in t.home if note_exists(x))
    print(f"{t.name}: {len(t.home)} home nodes ({home_with_note} with notes, {len(t.home) - home_with_note} planned), "
          f"{len(t.external)} external prerequisites, {len(t.edges)} edges")
    return problems


def cmd_check(args):
    if args.file:
        problems = check_one(Path(args.file))
        print("\n".join(problems) if problems else "No problems found.")
        sys.exit(1 if problems else 0)
    trees = load_trees()
    graph = Graph(trees)
    data = load_mastery()
    problems = []
    homes = {}
    for t in graph.trees:
        ids = t.titles()
        for i, title in t.external + t.home:
            if i != node_id(title):
                problems.append(f"{t.name}: id '{i}' should be '{node_id(title)}' for '{title}'")
        for i, title in t.home:
            if title in homes:
                problems.append(f"'{title}' is a home node in both {homes[title]} and {t.name}")
            homes[title] = t.name
        for a, b in t.edges:
            for x in (a, b):
                if x not in ids:
                    problems.append(f"{t.name}: edge uses undeclared node '{x}'")
        for i, title in t.external:
            if title not in graph.home_tree:
                problems.append(f"{t.name}: prerequisite '{title}' has no home tree")
    # cycles
    state = {}

    def visit(n, path):
        if state.get(n) == 1:
            problems.append("cycle: " + " -> ".join(path + [n]))
            return
        if state.get(n) == 2:
            return
        state[n] = 1
        for p in graph.prereqs.get(n, ()):
            visit(p, path + [n])
        state[n] = 2

    for n in list(graph.home_tree):
        visit(n, [])
    for title in data["nodes"]:
        if not note_exists(title):
            problems.append(f"mastery.yaml: '{title}' has no note (renamed or deleted?)")
        elif title not in graph.home_tree:
            problems.append(f"mastery.yaml: '{title}' is not in any tree")
    if TREE_TAGS_FILE.exists():
        tags_map = load_tree_tags()
        for t in graph.trees:
            if t.name not in tags_map:
                problems.append(f"tree_tags.yaml: no tag for tree '{t.name}'")
        for title, home in graph.home_tree.items():
            if note_exists(title):
                allowed = tag_trees(title)
                if home not in allowed:
                    problems.append(f"'{title}' lives in {home} but its tags {note_tags(title)} allow only {allowed or 'no tree'}")
    planned = sum(1 for t in graph.home_tree if not note_exists(t))
    legacy = [t.name for t in trees if t.legacy]
    print(f"{len(graph.trees)} converted tree(s), {len(graph.home_tree)} nodes ({planned} planned).")
    if legacy:
        print("Legacy trees:", ", ".join(legacy))
    print("\n".join(problems) if problems else "No problems found.")
    if problems:
        sys.exit(1)


