VAULT_ROOT = Path(__file__).resolve().parent.parent
NOTES_DIR = VAULT_ROOT / "Notes"
TREES_DIR = VAULT_ROOT / "Gamification" / "Skill Trees"
MASTERY_FILE = VAULT_ROOT / "Gamification" / "mastery.yaml"
TREE_TAGS_FILE = VAULT_ROOT / "Gamification" / "tree_tags.yaml"  # tree name -> subdomain tag

LEVEL_NAMES = ["Discovered", "Recall", "Apply", "Prove", "Wield", "Command"]
MAX_LEVEL = 5
MASTERED = 3
RUST_DAYS = {3: 60, 4: 90, 5: 180}
FRONTIER_SHARE = 2 / 3  # chance of a frontier question when review is also possible
RECENT_SKIP = 2  # don't quiz the same node again within this many questions
RECENT_KEEP = 10

STATE_BEGIN = "%% BEGIN STATE (generated by Scripts/skill_trees.py; do not edit)"
STATE_END = "%% END STATE"
STATS_BEGIN = "<!-- BEGIN STATS (generated by Scripts/skill_trees.py; do not edit) -->"
STATS_END = "<!-- END STATS -->"

NODE_RE = re.compile(r'^\s*([A-Za-z0-9_]+)\["(.*)"\]\s*$')
EDGE_RE = re.compile(r"^\s*([A-Za-z0-9_]+)\s*-->\s*([A-Za-z0-9_]+)\s*$")
SECTION_RE = re.compile(r"^\s*%% (PREREQUISITES|NODES|EDGES)\s*$")
GROUP_RE = re.compile(r"^\s*%% == (.+?) ==\s*$")
SOURCE_OPEN = "```skilltree"
SOURCE_NOTE = (
    "Graph structure: the single source for the diagrams above, edited by `/note` and "
    "`Scripts/skill_trees.py` (`add`, `edge`, `rename`). Everything above this heading is regenerated by `render`."
)

