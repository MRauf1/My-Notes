def prune_externals(text):
    """Drop external prerequisites that no edge uses."""
    while True:
        t_lines = text.split("\n")
        used = set()
        for l in t_lines:
            e = EDGE_RE.match(l)
            if e:
                used |= {e.group(1), e.group(2)}
        out, section, removed = [], None, False
        for l in t_lines:
            m = SECTION_RE.match(l)
            if m:
                section = m.group(1)
            n = NODE_RE.match(l)
            if section == "PREREQUISITES" and n and n.group(1) not in used:
                removed = True
                continue
            out.append(l)
        text = "\n".join(out)
        if not removed:
            return text


def without_node_lines(text, i, edges_into=False):
    """Remove declarations of node i (and, if edges_into, edges ending at i)."""
    out = []
    for l in text.split("\n"):
        n, e = NODE_RE.match(l), EDGE_RE.match(l)
        if n and n.group(1) == i:
            continue
        if edges_into and e and e.group(2) == i:
            continue
        out.append(l)
    return "\n".join(out)


def cmd_move(args):
    """Move a node to another tree (e.g. after retagging its note), carrying its prerequisite edges along."""
    trees = load_trees()
    graph = Graph(trees)
    title, x = args.title, node_id(args.title)
    src_name = graph.home_tree.get(title)
    if not src_name:
        sys.exit(f"'{title}' is not a node in any tree.")
    if src_name == args.tree:
        return print(f"'{title}' already lives in {args.tree}.")
    dst_path = TREES_DIR / f"{args.tree}.md"
    if not dst_path.exists():
        if not args.create:
            sys.exit(f"No tree '{args.tree}'. Pass --create to start a new one.")
        dst_path.write_text(new_tree_text(), encoding="utf-8")
    src, dst = find_tree(src_name), Tree(dst_path)
    src_titles = {**src.titles(), **dst.titles()}
    in_edges = [a for a, b in src.edges if b == x]
    still_prereq = any(a == x for a, _ in src.edges)

    text = without_node_lines(src.text, x, edges_into=True)
    if still_prereq:
        text = declare(text, title, "PREREQUISITES")
    src.path.write_text(prune_externals(text), encoding="utf-8")

    group = args.group
    if not group and dst.group_order:
        neighbours = [p for p in graph.prereqs.get(title, ())] + [d for d, ps in graph.prereqs.items() if title in ps]
        home_ids = dict(dst.home)
        counts = {}
        for nb in neighbours:
            i = node_id(nb)
            if i in home_ids:
                counts[dst.group[i]] = counts.get(dst.group[i], 0) + 1
        group = max(counts, key=counts.get) if counts else dst.group_order[-1]
    text = without_node_lines(dst.text, x)
    text = declare(text, title, "NODES", group)
    declared = {i for i, _ in dst.external + dst.home}
    for a in in_edges:
        a_title = src_titles[a]
        if a not in declared and graph.home_tree.get(a_title) != args.tree:
            text = declare(text, a_title, "PREREQUISITES")
            declared.add(a)
        text = add_edge_text(text, a_title, title)
    dst_path.write_text(prune_externals(text), encoding="utf-8")
    render_all()
    print(f"Moved '{title}': {src_name} -> {args.tree}" + (f" (group: {group})" if group else ""))


