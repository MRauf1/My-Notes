def insert_line(text, after_marker, line, before_marker):
    """Insert line at the end of the section that starts with after_marker."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip() == after_marker)
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip().startswith(before_marker))
    lines.insert(end, line)
    return "\n".join(lines)


def declare(text, title, section, group=None):
    label = title.replace('"', "#quot;")
    line = f'    {node_id(title)}["{label}"]'
    if section == "PREREQUISITES":
        return insert_line(text, "%% PREREQUISITES", line, "%% NODES")
    if group:
        header = f"    %% == {group} =="
        lines = text.split("\n")
        if header not in lines:
            text = insert_line(text, "%% NODES", header, "%% EDGES")
            lines = text.split("\n")
        start = lines.index(header)
        end = start + 1
        while end < len(lines) and not lines[end].strip().startswith(("%% ==", "%% EDGES")):
            end += 1
        lines.insert(end, line)
        return "\n".join(lines)
    return insert_line(text, "%% NODES", line, "%% EDGES")


def add_edge_text(text, a, b):
    line = f"    {node_id(a)} --> {node_id(b)}"
    if line in text.split("\n"):
        return text
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip() == "%% EDGES")
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip().startswith(("```", "%% BEGIN STATE")))
    lines.insert(end, line)
    return "\n".join(lines)


