def ancestors(graph, title):
    """All transitive prerequisites of a node, across every tree."""
    seen, stack = set(), list(graph.prereqs.get(title, ()))
    while stack:
        n = stack.pop()
        if n not in seen:
            seen.add(n)
            stack.extend(graph.prereqs.get(n, ()))
    return seen


def dependents_map(graph):
    out = {}
    for b, ps in graph.prereqs.items():
        for a in ps:
            out.setdefault(a, set()).add(b)
    return out


def tree_descendants(graph, deps, title, tree):
    """Transitive dependents of a node that live in `tree` (walking only through that tree)."""
    seen, stack = set(), [d for d in deps.get(title, ()) if graph.home_tree.get(d) == tree]
    while stack:
        n = stack.pop()
        if n not in seen:
            seen.add(n)
            stack.extend(d for d in deps.get(n, ()) if graph.home_tree.get(d) == tree)
    return seen


def placement_budget(n):
    lg = max(1, math.ceil(math.log2(n))) if n > 1 else 1
    return {2: min(12, 2 * lg), 3: min(6, lg)}


class Placement:
    """Placement state of one tree, derived from the recorded answers plus current levels."""

    def __init__(self, graph, data, tree):
        self.graph, self.data, self.tree = graph, data, tree
        self.state = data.setdefault("placement", {}).setdefault(tree, {"asked": []})
        self.nodes = [t for t, h in graph.home_tree.items() if h == tree and note_exists(t)]
        self.nodes.sort(key=lambda t: graph.order[t])
        self.budget = placement_budget(len(self.nodes))
        self.deps = dependents_map(graph)

    def asked(self, k):
        return [a for a in self.state["asked"] if a["level"] == k]

    def undetermined(self, k):
        failed = set()
        for a in self.asked(k):
            if a["result"] == "fail":
                failed |= {a["node"]} | tree_descendants(self.graph, self.deps, a["node"], self.tree)
        lo = k - 1  # stage k only considers nodes that reached k - 1 (all nodes for k = 2)
        return [t for t in self.nodes if t not in failed and level_of(self.data, t) < k
                and (k == 2 or level_of(self.data, t) >= lo)]

    def stage(self):
        for k in (2, 3):
            if self.undetermined(k) and len(self.asked(k)) < self.budget[k]:
                return k
        return None

    def pick(self, k):
        u = self.undetermined(k)
        us = set(u)
        best, best_score = None, -1
        for t in u:
            a = len(ancestors(self.graph, t) & us)
            d = len(tree_descendants(self.graph, self.deps, t, self.tree) & us)
            score = min(a, d) + 1
            if score > best_score:
                best, best_score = t, score
        return best


def tree_order(graph):
    """Trees bottom-up. Inter-tree prerequisite links are reduced to their net direction (ignoring
    differences below 2, i.e. stray single links), then topologically sorted; ties go to the tree with
    the shallower median node depth, and any remaining cycle is broken at the least-dependent tree."""
    names = [t.name for t in graph.trees if any(note_exists(x) for _, x in t.home)]
    w = {}
    for b, ps in graph.prereqs.items():
        for a in ps:
            ta, tb = graph.home_tree.get(a), graph.home_tree.get(b)
            if ta and tb and ta != tb and ta in names and tb in names:
                w[(ta, tb)] = w.get((ta, tb), 0) + 1
    net = {(a, b): v for (a, b), v in w.items() if v - w.get((b, a), 0) >= 2}
    memo = {}
    depth = {n: statistics.median(graph.depth(x, memo) for x, h in graph.home_tree.items() if h == n and note_exists(x))
             for n in names}
    remaining, order = set(names), []
    while remaining:
        free = [t for t in remaining if not any((u, t) in net for u in remaining if u != t)]
        if free:
            pick = min(free, key=lambda t: (depth[t], t))
        else:
            pick = min(remaining, key=lambda t: (sum(v for (a, b), v in net.items() if b == t and a in remaining), depth[t], t))
        order.append(pick)
        remaining.discard(pick)
    return order


