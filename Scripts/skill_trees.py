def recently_active_trees(graph):
    """Weight per tree: 1 + home notes changed in git in the last 30 days."""
    weights = {t.name: 1 for t in graph.trees}
    try:
        out = subprocess.run(
            ["git", "log", "--since=30 days ago", "--name-only", "--pretty=format:", "--", "Notes/"],
            cwd=VAULT_ROOT, capture_output=True, text=True, check=True,
        ).stdout
    except Exception:
        return weights
    for path in set(out.split("\n")):
        title = Path(path).stem
        if title in graph.home_tree:
            weights[graph.home_tree[title]] += 1
    return weights


