#!/usr/bin/env python3
"""Skill-tree engine: mastery levels, prerequisite gating, rust, and rendering.

Usage:
    python3 skill_trees.py status [--tree NAME]
    python3 skill_trees.py next [--tree NAME] [--node TITLE]
    python3 skill_trees.py record TITLE --level K --result correct|partial|incorrect [--hints N]
    python3 skill_trees.py stuck TITLE --required K
    python3 skill_trees.py add TREE TITLE [--prereq TITLE ...] [--group NAME]
    python3 skill_trees.py edge FROM_TITLE TO_TITLE
    python3 skill_trees.py rename OLD_TITLE NEW_TITLE
    python3 skill_trees.py move TITLE TREE [--group NAME]
    python3 skill_trees.py tree-for TITLE
    python3 skill_trees.py place-order
    python3 skill_trees.py place-next [TREE]
    python3 skill_trees.py place-record TITLE --level K --result pass|fail
    python3 skill_trees.py place-status [TREE]
    python3 skill_trees.py place-reset TREE
    python3 skill_trees.py render
    python3 skill_trees.py check

Requires: PyYAML (`python-yaml`).

Tree files (Gamification/Skill Trees/<Field>.md) end with a `skilltree` source
block holding the graph structure (the only part edited by hand or by `add`,
`edge`, `rename`):

    ```skilltree
        %% PREREQUISITES
        n_measure_space["Measure Space"]          <- nodes whose home is another tree
        %% NODES
        %% == Group Name ==                        <- optional group comments
        n_sigma_algebra["Sigma-Algebra"]           <- this tree's own (home) nodes
        %% EDGES
        n_sigma_algebra --> n_measure_space        <- prerequisite --> dependent
    ```

Everything above the source block is regenerated by `render`: a stats block,
then one small Mermaid diagram per group (a group's home nodes plus their
prerequisites from elsewhere). Per-group diagrams keep each one far below
Mermaid's limits (50k characters, 500 edges). Files without a `%% NODES`
marker are legacy trees and are ignored. Node labels are note titles exactly (so Obsidian's
`internal-link` class makes them clickable); node IDs are derived from the
title by node_id(). A label with no matching Notes/<Title>.md is "planned".

Levels (stored in Gamification/mastery.yaml, keyed by note title):
    0 Discovered  1 Recall  2 Apply  3 Prove (= Mastered)  4 Wield  5 Command
Rules:
    - Attempting level k on a node requires every prerequisite at level
      >= min(k, 3). Planned prerequisites never satisfy this.
    - Level-up to k: 1 correct answer for k = 1, 2 correct answers otherwise.
      A correct answer needing 2+ hints, or a partial answer, changes nothing;
      an incorrect answer resets progress (no level loss).
    - Mastered nodes (level >= 3) go rusty after RUST_DAYS[level] days without
      a test. A rust check is asked at the current level: pass refreshes it,
      fail drops one level.
    - Being stuck on an ability at level k (via /stuck) sets the level to
      min(level, k - 1).
Placement (adaptive, per tree, bottom-up across trees):
    - Stage L2 then stage L3. Each question goes to the undetermined node that
      best halves the rest (max of min(#undetermined ancestors, #undetermined
      descendants) + 1). Pass at k raises the node and all its ancestors (in
      every tree) to k; fail marks the node and its in-tree descendants as
      below k for that stage. Levels are only ever raised.
    - Placed levels are provisional: the next quiz on such a node is a
      "placement check" at its current level (fail drops one level).
"""

